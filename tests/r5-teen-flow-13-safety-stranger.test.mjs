test("safety.html without scripts: every section has real static text taken from safety.json, plus a noscript note", () => {
  const doc = new JSDOM(read("safety.html")).window.document;
  for (const s of D.sections) {
    const p = doc.querySelector(`#sbody-${s.id} > p`);
    assert.ok(p, "static paragraph in " + s.id);
    const t = norm(p.textContent);
    assert.ok(t.length > 40, s.id + " has real text");
    assert.ok(s.plain.startsWith(t), s.id + " static text is the start of data/safety.json plain");
    assert.doesNotMatch(t, /Loading/);
    // Generated by tools/build.py from data/safety.json: every point is a card with its own source link.
    const cards = [...doc.querySelectorAll(`#sbody-${s.id} article.card`)];
    assert.equal(cards.length, s.points.length, s.id + " has one static card per data point");
    s.points.forEach((pt, i) => {
      const a = cards[i].querySelector("a");
      assert.equal(a.getAttribute("href"), pt.url, s.id + " point " + i + " links to its source");
      assert.equal(norm(a.textContent), pt.source);
      assert.ok(cards[i].textContent.includes(pt.text), s.id + " point " + i + " text is static");
    });
  }
  const main = doc.querySelector("main");
  const ns = main.querySelectorAll("noscript");
  assert.equal(ns.length, 1);
  assert.match(ns[0].textContent, /needs JavaScript/);
  const tops = [...doc.querySelectorAll("#sTop a[href^='tel:']")].map((a) => a.getAttribute("href"));
  const want = D.hotlines.filter((h) => h.top).flatMap((h) => h.numbers.map((n) => "tel:" + n.tel));
  assert.deepEqual(tops, want, "national numbers are in the static html");
});

