test("safety page: all states list shows only numbers that are in permits.json", async () => {
  const { document, errors } = await loadPage("safety.html"); await tick(300);
  assert.deepEqual(errors, []);
  const cards = [...document.querySelectorAll("#sStateCalls [data-state]")];
  const ids = Object.keys(P.states).filter((k) => !["ca", "ga", "ny", "il"].includes(k));
  const hasNum = (k) => /\d{3}\D{1,3}\d{3}\D\d{4}/.test(P.states[k].call);
  assert.deepEqual(cards.map((c) => c.dataset.state), [...ids.filter(hasNum), ...ids.filter((k) => !hasNum(k))], "states with a number come first");
  for (const c of cards) {
    const st = P.states[c.dataset.state];
    if (hasNum(c.dataset.state)) assert.ok(c.textContent.includes(st.call), c.dataset.state + " shows the card's call line as written");
    else {
      assert.ok(c.textContent.includes("No phone number found. Use the agency website."), c.dataset.state + " says no number is found");
      assert.doesNotMatch(c.textContent, /No phone number is listed|blocked our reader|confirm there/, c.dataset.state + " shows no internal note");
    }
    const given = (st.call.match(/\d{3}\D{1,3}\d{3}\D\d{4}/g) || []).map((x) => x.replace(/\D/g, "").slice(-10));
    const tels = [...c.querySelectorAll('a[href^="tel:"]')].map((a) => a.getAttribute("href").slice(-10));
    assert.deepEqual(tels, given, c.dataset.state + " has links only for numbers in the data");
    assert.ok(c.querySelector(`a[href="permit.html?state=${c.dataset.state}"]`));
  }
  assert.ok(document.querySelector('#sStateCalls a[href="tel:+13172322655"]'), "Indiana number");
  assert.equal(document.querySelectorAll('#sStateCalls [data-state="tx"] a[href^="tel:"]').length, 0, "Texas has no number, none is made up");
  assert.doesNotMatch(document.getElementById("sStateCalls").textContent, /undefined|NaN/);
});

test("safety page: picking Indiana shows only Indiana plus the national numbers", async () => {
  const { document, window } = await loadPage("safety.html"); await tick(300);
  const sel = document.getElementById("sState");
  sel.value = "in"; sel.dispatchEvent(new window.Event("change", { bubbles: true }));
  assert.deepEqual([...document.querySelectorAll("#sStateCalls [data-state]")].map((c) => c.dataset.state), ["in"]);
  const groups = [...document.querySelectorAll("#sbody-call .hgroup")].filter((g) => !g.hidden).map((g) => g.dataset.group);
  assert.deepEqual(groups, ["National"]);
  assert.match(document.getElementById("sCallStatus").textContent, /Indiana/);
  assert.equal(document.getElementById("sec-statecalls").hidden, false);
  const next = [...document.querySelectorAll("#sNext a")].find((a) => a.textContent === "Use the work permit finder");
  assert.equal(next.getAttribute("href"), "permit.html?state=in");
});

test("safety page: picking California hides the extra list, ?state=wa starts on Washington", async () => {
  let r = await loadPage("safety.html"); await tick(300);
  const sel = r.document.getElementById("sState");
  sel.value = "ca"; sel.dispatchEvent(new r.window.Event("change", { bubbles: true }));
  assert.equal(r.document.getElementById("sec-statecalls").hidden, true);
  r = await loadPage("safety.html", { search: "?state=wa" }); await tick(300);
  assert.equal(r.document.getElementById("sState").value, "wa");
  assert.deepEqual([...r.document.querySelectorAll("#sStateCalls [data-state]")].map((c) => c.dataset.state), ["wa"]);
});

